"""Read-only G1A-R diagnostics; pending approval files never activate themselves."""
import argparse
import csv
import json
import time
from .policy import ROOT, fingerprint
from .policy_sources import native_catalogue
from .catalogue_repair import load_catalogue, load_batch, BASE
from .inference import recommend_profile


def inspect_repair():
    start = time.perf_counter()
    originals = json.loads((ROOT / 'ml/data/review/phase2/calibration-v1/profiles.synthetic.json').read_text())
    profiles = [json.loads((ROOT / 'ml/tests/fixtures/phase2_profile.synthetic.json').read_text())] + originals
    before_roles, after_roles = native_catalogue(), load_catalogue()
    batch = load_batch()
    before = [recommend_profile(p, before_roles) for p in profiles]
    after = [recommend_profile(p, after_roles) for p in profiles]
    pairs = [{'profile_id': p['profile_id'], 'profile_family_id': p['profile_family_id'],
              'profile_version': p['version'], 'role_id': role['role_id'], 'milestone_id': None,
              'before_eligible': before[i]['derivations'][j]['eligible'],
              'after_eligible': after[i]['derivations'][j]['eligible'],
              'after_reasons': after[i]['derivations'][j]['exceptions']}
             for i, p in enumerate(profiles) for j, role in enumerate(after_roles)]
    primary = []
    for role in after_roles:
        missing = next(d['missing_evidence'] for r in after for d in r['derivations'] if d['role_id'] == role['role_id'])
        primary.append({'role_id': role['role_id'], 'milestone_id': None,
            'category': 'missing_role_milestone_definition', 'missing_fields': missing,
            'affected_pair_count': len(profiles), 'counting_scope': 'unique primary failures for this role',
            'provenance': 'Original criteria are Codex-assisted proposals; native occupation identity is source-derived.',
            'source_availability': 'Pinned O*NET skill rows and public learning context exist; no compatible accepted bounded template or defensible effort estimate exists.',
            'repair': 'One inactive proposed batch supplies concrete scope, anchors, scenarios, tags and resources; real batch decision and six task-effort ranges still required.'})
    mappings = json.loads((ROOT / 'ml/data/review/source_mappings.pending.json').read_text())
    with (ROOT / 'ml/data/annotations/personal_fit_annotations.csv').open() as stream:
        annotations = list(csv.DictReader(stream))
    return {'gate': 'G1A-R', 'adapter_version': 'g1ar-catalogue-adapter-v1',
        'catalogue_completeness': 'partial', 'empirical_status': 'not_evaluated',
        'before_scored_pairs': sum(len(r['recommendation']['options']) for r in before),
        'after_scored_pairs': sum(len(r['recommendation']['options']) for r in after),
        'actual_pair_count': len(pairs), 'unscored_pair_count': sum(not p['after_eligible'] for p in pairs),
        'profiles': [{'profile_id': p['profile_id'], 'family_id': p['profile_family_id'], 'version': p['version'], 'data_class': p['data_class']} for p in profiles],
        'pair_inventory': pairs, 'primary_root_causes': primary,
        'overlapping_dependencies': [
            {'category': 'missing_profile_measurements', 'affected_pair_count': len(pairs),
             'overlaps_primary_counts': True, 'missing': ['Version-bound anchored criterion answers', 'Explicit interest/work-style utilities', 'Confirmed resource access and hard-constraint checks'],
             'repair': 'Keep six existing profiles incomplete. Supply explicit new answers only against an accepted template; no free-text imputation.'},
            {'category': 'optional_crosswalk_unresolved', 'candidate_count': len(mappings['candidates']), 'blocked_baseline_pairs': 0,
             'source_side_taxonomy_edition': '2019', 'remaining': ['Mapping relation applicability', 'ESCO version/scope and target-geography applicability', 'Specific crosswalk reuse terms'],
             'repair': 'Use the native identifiers; no mapping was adopted.'},
            {'category': 'independent_labels_absent', 'annotation_csv_rows': len(annotations), 'blocked_baseline_pairs': 0,
             'repair': 'Only empirical agreement evaluation/learner comparison need independent labels; no labels are generated by this gate.'}],
        'deterministic_repairs': {'taxonomy_edition': '2019', 'database_version': '31.0',
            'criterion_weights': [c for r in after_roles for c in r['criterion_policy_defaults']],
            'adopted_optional_mappings': 0},
        'proposal': {'batch_id': batch['batch_id'], 'status': batch['status'], 'active': batch['active'],
            'templates': len(batch['milestone_templates']), 'synthetic_assessment_instances': len(batch['assessment_instances']),
            'unknown_task_effort_ranges': sum(t['effort'] is None for m in batch['milestone_templates'] for t in m['tasks']),
            'path': BASE + '/milestone_batch.proposed.json', 'decision_path': BASE + '/batch_decision.pending.json'},
        'before_catalogue_fingerprint': fingerprint(before_roles), 'after_catalogue_fingerprint': fingerprint(after_roles),
        'before_service': before, 'after_service': after, 'repaired_reference_projection': after_roles,
        'live_service_exercised': {'python_callable': True, 'http_endpoint': False, 'frontend': False},
        'new_complete_profiles_created': 0, 'reason': 'No actual role milestone is accepted; creating answered profiles now would not establish real-role eligibility.',
        'execution_location': 'local CPU, existing ml/.venv', 'elapsed_seconds': round(time.perf_counter() - start, 6)}


def main():
    argparse.ArgumentParser(description=__doc__).parse_args()
    print(json.dumps(inspect_repair(), indent=2, sort_keys=True, allow_nan=False))


if __name__ == '__main__':
    main()
